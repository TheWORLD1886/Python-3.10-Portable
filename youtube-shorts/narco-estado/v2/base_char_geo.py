def chaikin(pts, it=2):
    p = np.array(pts, float)
    for _ in range(it):
        q = [p[0]]
        for a, b in zip(p[:-1], p[1:]): q += [a * .75 + b * .25, a * .25 + b * .75]
        q.append(p[-1]); p = np.array(q)
    return p
